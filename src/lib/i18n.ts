export type Lang = "ca" | "es" | "en";
export const LANGS: { id: Lang; label: string }[] = [
  { id: "ca", label: "CAT" },
  { id: "es", label: "ES" },
  { id: "en", label: "EN" },
];

const KEY = "lang";

function detect(): Lang {
  try {
    const saved = localStorage.getItem(KEY);
    if (saved === "ca" || saved === "es" || saved === "en") return saved;
  } catch {
    /* private mode */
  }
  const nav = navigator.language.toLowerCase();
  return nav.startsWith("ca") ? "ca" : nav.startsWith("es") ? "es" : "en";
}

export const lang: Lang = detect();
// Guarded so node scripts (test:city-actions) can import modules that use t().
if (typeof document !== "undefined") document.documentElement.lang = lang;
export const locale = lang === "ca" ? "ca-ES" : lang === "es" ? "es-ES" : "en-GB";

export function setLang(next: Lang) {
  try {
    localStorage.setItem(KEY, next);
  } catch {
    /* private mode */
  }
  location.reload();
}

export function t(en: string, vars?: Record<string, string | number>): string {
  let out = lang === "en" ? en : DICT[lang][en] ?? en;
  for (const [k, v] of Object.entries(vars ?? {})) out = out.replaceAll(`{${k}}`, String(v));
  return out;
}

